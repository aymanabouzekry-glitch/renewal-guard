export function useTranslation() {
  const [locale, setLocale] = useState<Locale>("en");

  useEffect(() => {
    const saved = (localStorage.getItem("rg_locale") as Locale) || "en";
    setLocale(saved);
    document.documentElement.lang = saved;
    document.documentElement.dir = saved === "ar" ? "rtl" : "ltr";

    const handleLocaleChange = () => {
      const updated = (localStorage.getItem("rg_locale") as Locale) || "en";
      setLocale(updated);
      document.documentElement.lang = updated;
      document.documentElement.dir = updated === "ar" ? "rtl" : "ltr";
    };

    window.addEventListener("rg-locale-change", handleLocaleChange);
    return () => window.removeEventListener("rg-locale-change", handleLocaleChange);
  }, []);

  const toggleLanguage = () => {
    const nextLocale: Locale = locale === "en" ? "ar" : "en";
    localStorage.setItem("rg_locale", nextLocale);
    setLocale(nextLocale);
    document.documentElement.lang = nextLocale;
    document.documentElement.dir = nextLocale === "ar" ? "rtl" : "ltr";
    window.dispatchEvent(new Event("rg-locale-change"));
  };

  return {
    locale,
    t: dictionary[locale],
    toggleLanguage,
    isRtl: locale === "ar",
  };
}